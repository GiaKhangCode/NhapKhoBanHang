package com.thebangcoffee.model;

public class CongThuc {
    private String maCongThuc;
    private String maBienThe;
    private String maNL;
    private double dinhLuong;

    public CongThuc() {}

    public String getMaCongThuc() { return maCongThuc; }
    public void setMaCongThuc(String maCongThuc) { this.maCongThuc = maCongThuc; }
    public String getMaBienThe() { return maBienThe; }
    public void setMaBienThe(String maBienThe) { this.maBienThe = maBienThe; }
    public String getMaNL() { return maNL; }
    public void setMaNL(String maNL) { this.maNL = maNL; }
    public double getDinhLuong() { return dinhLuong; }
    public void setDinhLuong(double dinhLuong) { this.dinhLuong = dinhLuong; }
}
